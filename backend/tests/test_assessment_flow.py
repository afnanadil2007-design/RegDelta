"""End-to-end assessment: launch → run → findings → evidence → decision → refresh.

Runs the real graph with the deterministic provider and the real reranker over
the seeded corpus. Starlette's TestClient executes the background task before
returning from the POST, so the run is complete when the next request is made.
"""

from __future__ import annotations

import json
import uuid

import pytest
from fastapi.testclient import TestClient

from app.main import create_app
from app.services.assessment import create_assessment
from tests.conftest import SeededCorpus

MARGIN_2024 = "SEBI/HO/MIRSD/MIRSD-PoD/CIR/P/2024/17"


@pytest.fixture(scope="module")
def client() -> TestClient:
    return TestClient(create_app())


@pytest.fixture(scope="module")
def finished_run(client: TestClient, corpus: SeededCorpus) -> dict:
    response = client.post(
        "/api/assessments",
        json={"circular_id": corpus.id_of(MARGIN_2024), "policy_pack_id": corpus.policy_pack_id},
    )
    assert response.status_code == 202, response.text
    run_id = response.json()["run_id"]
    detail = client.get(f"/api/assessments/{run_id}")
    assert detail.status_code == 200
    return detail.json()


def test_run_completes_with_its_provider_recorded(finished_run: dict) -> None:
    assert finished_run["status"] == "COMPLETED", finished_run["status_detail"]
    assert finished_run["provider"] == {
        "name": "deterministic",
        "model": "regdelta-rules-v1",
        "deterministic": True,
    }
    assert finished_run["graph_version"] == "v3"
    assert finished_run["usage"]["cost_complete"] is True
    assert finished_run["usage"]["estimated_cost_usd"] == 0.0
    assert finished_run["failed_tasks"] == 0
    assert finished_run["completed_at"] is not None


def test_every_obligation_gets_a_finding(finished_run: dict) -> None:
    counts = finished_run["counts"]
    assert counts["total"] == len(finished_run["findings"]) > 0
    assert counts["assessed_obligations"] == finished_run["obligation_count"]
    assert counts["decision_pending"] == counts["total"]


def test_verified_findings_point_at_text_that_exists(
    client: TestClient, finished_run: dict
) -> None:
    circular = client.get(f"/api/circulars/{finished_run['circular_id']}").json()
    full_text = circular["full_text"]
    verified = [f for f in finished_run["findings"] if f["quote_status"] == "VERIFIED"]
    assert verified, "the deterministic judge quotes verbatim, so some quotes must verify"

    for finding in verified:
        obligation = full_text[finding["obligation_char_start"] : finding["obligation_char_end"]]
        assert obligation == finding["obligation_text"]
        quote = full_text[finding["circular_span_start"] : finding["circular_span_end"]]
        assert quote and quote in obligation
        if finding["clause_span_start"] is not None:
            local = finding["clause_span_start"] - finding["clause_char_start"]
            length = finding["clause_span_end"] - finding["clause_span_start"]
            assert finding["clause_text"][local : local + length].strip()


def test_findings_without_a_judgement_claim_no_score(finished_run: dict) -> None:
    for finding in finished_run["findings"]:
        if finding["quote_status"] == "NOT_APPLICABLE":
            assert finding["model_confidence"] is None
            assert finding["policy_clause_id"] is None
            assert finding["impact_type"] == "NO_MATCH"


def test_memo_is_labelled_as_rule_based(finished_run: dict) -> None:
    assert finished_run["memo"].startswith("Generated by the deterministic demo provider")


def test_memo_counts_located_quotations_and_claims_nothing_more(finished_run: dict) -> None:
    statuses = [f["quote_status"] for f in finished_run["findings"]]
    memo = finished_run["memo"]
    # The memo covers findings with located quotes and those with no clause.
    assert f"{statuses.count('VERIFIED')} with quotations located in the circular" in memo
    assert f"{statuses.count('NOT_APPLICABLE')} with no clause to compare" in memo
    assert "verified" not in memo.lower()


def test_a_decision_persists_across_a_refresh(client: TestClient, finished_run: dict) -> None:
    finding = finished_run["findings"][0]
    response = client.post(
        f"/api/assessments/findings/{finding['id']}/decision", json={"decision": "ACCEPTED"}
    )
    assert response.status_code == 200
    assert response.json()["analyst_decision"] == "ACCEPTED"
    assert response.json()["decided_at"] is not None

    refreshed = client.get(f"/api/assessments/{finished_run['run_id']}").json()
    (same,) = [f for f in refreshed["findings"] if f["id"] == finding["id"]]
    assert same["analyst_decision"] == "ACCEPTED"
    assert refreshed["counts"]["decision_accepted"] == 1

    reset = client.post(
        f"/api/assessments/findings/{finding['id']}/decision", json={"decision": "PENDING"}
    )
    assert reset.json()["decided_at"] is None


def test_an_invalid_decision_is_rejected(client: TestClient, finished_run: dict) -> None:
    finding = finished_run["findings"][0]
    response = client.post(
        f"/api/assessments/findings/{finding['id']}/decision", json={"decision": "MAYBE"}
    )
    assert response.status_code == 422
    assert response.json()["error"]["code"] == "invalid_request"


def test_a_decision_on_an_unknown_finding_is_404(client: TestClient, corpus) -> None:
    response = client.post(
        "/api/assessments/findings/99999999/decision", json={"decision": "REJECTED"}
    )
    assert response.status_code == 404
    assert response.json()["error"]["code"] == "finding_not_found"


def test_the_trace_records_each_node(client: TestClient, finished_run: dict) -> None:
    steps = client.get(f"/api/assessments/{finished_run['run_id']}/steps").json()
    nodes = [s["node"] for s in steps]
    assert nodes[0] == "plan_assessment"
    assert nodes[-1] == "synthesize_memo"
    assert {"retrieve_clauses", "judge_impact", "verify_grounding"} <= set(nodes)
    assert all(s["status"] == "OK" for s in steps)
    assert [s["seq"] for s in steps] == sorted(s["seq"] for s in steps)
    judged = [s for s in steps if s["node"] == "judge_impact"]
    assert all(s["obligation_id"] and s["clause_number"] and s["attempt"] for s in judged)


def test_stream_of_a_finished_run_is_a_snapshot_then_done(
    client: TestClient, finished_run: dict
) -> None:
    events: list[tuple[str, dict]] = []
    with client.stream("GET", f"/api/assessments/{finished_run['run_id']}/stream") as response:
        name = None
        for line in response.iter_lines():
            if line.startswith("event:"):
                name = line.split(":", 1)[1].strip()
            elif line.startswith("data:") and name:
                events.append((name, json.loads(line.split(":", 1)[1])))
    assert [n for n, _ in events] == ["snapshot", "done"]
    snapshot = events[0][1]
    assert snapshot["status"] == "COMPLETED"
    assert len(snapshot["steps"]) >= 4
    assert events[1][1]["status"] == "COMPLETED"


def test_stream_for_an_unknown_run_reports_an_error(client: TestClient, corpus) -> None:
    with client.stream("GET", f"/api/assessments/{uuid.uuid4()}/stream") as response:
        body = "".join(response.iter_text())
    assert "event: error" in body


@pytest.mark.asyncio
async def test_a_second_launch_while_one_is_active_is_refused(
    client: TestClient, corpus: SeededCorpus
) -> None:
    # A PENDING run (not executed) occupies the slot for this circular + pack.
    kyc = corpus.id_of("SEBI/HO/MIRSD/MIRSD-PoD/CIR/P/2024/31")
    run_id = await create_assessment(kyc, corpus.policy_pack_id)

    response = client.post(
        "/api/assessments", json={"circular_id": kyc, "policy_pack_id": corpus.policy_pack_id}
    )
    assert response.status_code == 409
    error = response.json()["error"]
    assert error["code"] == "assessment_in_progress"
    assert error["detail"]["run_id"] == str(run_id)
